import { catalogId, record } from '../catalog/contracts';
import { contactWebsite } from '../providers/contracts';
import { weeklyHours } from '../providers/hours';
import { readReportTarget } from './targets.server';
import {
  ReportError,
  issueLabels,
  type ReportInput,
  type ReportReceipt,
  type ReportTarget,
  type ReportPrice,
} from './contracts';

export class CorrectionRepository {
  constructor(private readonly db: D1Database) {}

  async submit(
    input: ReportInput,
    reporterId: string,
    now = Date.now(),
  ): Promise<{ id: string; target: ReportTarget }> {
    const target = await readReportTarget(this.db, { target: input.target, id: input.id });
    if (!target) throw new ReportError('not_found');
    const id = crypto.randomUUID();
    try {
      await this.db
        .prepare(
          `INSERT INTO correction_reports(id, reporter_id, target_type, target_id, provider_id, branch_id, listing_id, issue_type,
        observed_revision, observed_price_id, target_snapshot, details, suggested_correction, evidence_url, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
        )
        .bind(
          id,
          reporterId,
          target.kind,
          target.id,
          target.providerId,
          target.branchId,
          target.listingId,
          input.issue,
          input.observedRevision,
          input.observedPriceId,
          JSON.stringify(target),
          input.details,
          input.suggestedCorrection,
          input.evidenceUrl,
          now,
        )
        .run();
      return { id, target };
    } catch (error) {
      const message = error instanceof Error ? error.message : '';
      if (
        message.includes('report_duplicate') ||
        message.includes('correction_reports.reporter_id')
      )
        throw new ReportError('duplicate');
      if (message.includes('report_rate_limit')) throw new ReportError('rate_limited');
      if (message.includes('report_target_changed') || message.includes('pricing_conflict'))
        throw new ReportError('target_changed');
      if (message.includes('report_invalid') || message.includes('FOREIGN KEY constraint failed'))
        throw new ReportError('invalid_request');
      throw new ReportError('unavailable');
    }
  }

  async ownReceipt(id: unknown, reporterId: string): Promise<ReportReceipt | null> {
    const row = await this.db
      .prepare('SELECT * FROM correction_reports WHERE id = ? AND reporter_id = ?')
      .bind(catalogId(id), reporterId)
      .first<Record<string, unknown>>();
    if (row === null) return null;
    if (
      typeof row.target_snapshot !== 'string' ||
      typeof row.details !== 'string' ||
      typeof row.created_at !== 'number' ||
      !Number.isSafeInteger(row.created_at) ||
      (row.status !== 'pending' && row.status !== 'accepted' && row.status !== 'rejected') ||
      typeof row.issue_type !== 'string' ||
      !Object.hasOwn(issueLabels, row.issue_type)
    )
      throw new Error('Invalid stored correction report');
    const issue = Object.keys(issueLabels).find((key) => key === row.issue_type);
    if (!issue || !isIssue(issue)) throw new Error('Invalid stored report issue');
    const snapshot: unknown = JSON.parse(row.target_snapshot);
    const target = decodeSnapshot(snapshot);
    return {
      id: catalogId(row.id),
      issue,
      status: row.status,
      createdAt: row.created_at,
      target,
      details: row.details,
      suggestedCorrection: nullable(row.suggested_correction),
      evidenceUrl: evidenceLink(row.evidence_url),
    };
  }
}
function nullable(value: unknown): string | null {
  if (value === null) return null;
  if (typeof value !== 'string') throw new Error('Invalid report text');
  return value;
}
function isIssue(value: string): value is keyof typeof issueLabels {
  return Object.hasOwn(issueLabels, value);
}

export function decodeSnapshot(value: unknown): ReportTarget {
  const row = record(value);
  if (
    (row.kind !== 'listing' && row.kind !== 'branch' && row.kind !== 'provider') ||
    typeof row.providerName !== 'string' ||
    typeof row.revision !== 'number' ||
    !Number.isSafeInteger(row.revision) ||
    row.revision < 1
  )
    throw new Error('Invalid report snapshot');
  // Snapshots are generated by readReportTarget and retained unchanged by database constraints.
  // Validate their public shape before returning a private receipt.
  const priceRow = row.price === null ? null : record(row.price);
  const status = priceRow?.status;
  if (
    priceRow &&
    (typeof priceRow.amountMinor !== 'number' ||
      !Number.isSafeInteger(priceRow.amountMinor) ||
      priceRow.amountMinor < 1 ||
      (status !== 'verified' && status !== 'unverified' && status !== 'disputed'))
  )
    throw new Error('Invalid report price snapshot');
  const price: ReportPrice | null =
    priceRow && (status === 'verified' || status === 'unverified' || status === 'disputed')
      ? {
          id: catalogId(priceRow.id),
          amountMinor: Number(priceRow.amountMinor),
          status,
          sourceId: priceRow.sourceId === null ? null : catalogId(priceRow.sourceId),
          sourceRow: snapshotRow(priceRow.sourceRow),
          verifiedAt: nullable(priceRow.verifiedAt),
          effectiveDate: nullable(priceRow.effectiveDate),
          verificationMethod: nullable(priceRow.verificationMethod),
        }
      : null;
  return {
    kind: row.kind,
    id: catalogId(row.id),
    revision: row.revision,
    providerId: catalogId(row.providerId),
    providerName: row.providerName,
    branchId: row.branchId === null ? null : catalogId(row.branchId),
    listingId: row.listingId === null ? null : catalogId(row.listingId),
    branchName: nullable(row.branchName),
    serviceName: nullable(row.serviceName),
    providerServiceName: nullable(row.providerServiceName),
    address: nullable(row.address),
    phone: nullable(row.phone),
    website: nullable(row.website),
    openingHours: decodeHours(row.openingHours),
    price,
  };
}
function evidenceLink(value: unknown): string | null {
  const url = contactWebsite(value);
  if (url && !url.startsWith('https://')) throw new Error('Invalid stored evidence URL');
  return url;
}
function decodeHours(value: unknown) {
  return value === null ? null : weeklyHours(value);
}
function snapshotRow(value: unknown): number | null {
  if (value === null) return null;
  if (typeof value !== 'number' || !Number.isSafeInteger(value) || value < 1)
    throw new Error('Invalid report source row');
  return value;
}
